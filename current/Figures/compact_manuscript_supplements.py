"""Lay out the recorded S3 table in two parts without changing its cells.

Run after rebuild_supplementary_tables.py. The standalone table remains intact;
the manuscript gets a continued table and room for references beneath part two.
"""
from pathlib import Path
import argparse
import re


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--paper', type=Path, required=True)
    args = parser.parse_args()
    root = Path(__file__).resolve().parent
    source = (root / 'tables/TS3_repeated_times_grouped.tex').read_text(encoding='utf-8')
    head, rest = source.split('\\midrule\n', 1)
    body, tail = rest.split('\\bottomrule', 1)
    start_vg = body.index(r'\multirow{12}{*}{VG}')
    split = body.rfind(r'\specialrule', 0, start_vg)
    assert split >= 0
    first_body = body[:split].rstrip() + '\n'
    second_body = body[start_vg:]
    assert sum('&' in line for line in body.splitlines()) == 68
    assert sum('&' in line for line in (first_body + second_body).splitlines()) == 68

    first = head.replace(r'\begin{table*}[!t]', r'\begin{table*}[!tp]')
    first += '\\midrule\n' + first_body
    first += '\\bottomrule\n\\end{tabular*}\n\\end{table*}\n'

    continued = re.sub(r'\\begin\{table\*\}\[[^]]*\]\s*', '', head)
    continued = re.sub(r'\\caption\{[^}]*\}\\label\{[^}]*\}',
                       lambda _: r'\par\noindent\makebox[\textwidth][l]{\fontsize{9}{11}\selectfont\textsf{\textbf{Table~\thetable\ (continued)}}}\par'
                       '\n' + r'\noindent\makebox[\textwidth][l]{\fontsize{9}{11}\selectfont\textsf{Repeated total optimization times.}}\par\smallskip',
                       continued)
    continued += '\\midrule\n' + second_body + '\\bottomrule' + tail
    continued = continued.replace(r'\end{table*}', '')
    continued = continued.replace(r'\begin{tabular*}', r'\begingroup\sffamily' + '\n' + r'\begin{tabular*}')
    continued = continued.replace(r'\end{tabular*}', r'\end{tabular*}\endgroup')
    tables = args.paper / 'tables'
    tables.mkdir(parents=True, exist_ok=True)
    (tables / 'TS3_repeated_times_first.tex').write_text(first, encoding='utf-8')
    (tables / 'TS3_repeated_times_continued.tex').write_text(continued, encoding='utf-8')
    (tables / 'TS3_repeated_times.tex').write_text(r'''% Generated by compact_manuscript_supplements.py; data unchanged.
\input{tables/TS3_repeated_times_first}
% Reset column dimensions and place the final wide block above the references.
\twocolumn[{%
\begin{minipage}{\textwidth}
\input{tables/TS3_repeated_times_continued}
\end{minipage}\par\vspace{12pt}
}]
''', encoding='utf-8')
    first_rows = sum('&' in line for line in first_body.splitlines())
    second_rows = sum('&' in line for line in second_body.splitlines())
    print('S3: %d + %d rows; all 68 rows and all recorded values retained.' % (first_rows, second_rows))


if __name__ == '__main__':
    main()
